import { Field as BaseField } from '@base-ui/react/field';
import { mergeProps } from '@base-ui/react/merge-props';
import { createContext, useContext, type ComponentProps, type HTMLAttributes, type ReactNode } from 'react';
import { cx } from '../../utils/cx';
import styles from './Field.module.css';

/** What the parts need from the root: whether `error` is set, and whether the label is a native `<label>`. */
const FieldContext = createContext({ invalid: false, nativeLabel: true });

export interface FieldProps extends Omit<ComponentProps<typeof BaseField.Root>, 'className' | 'render' | 'children'> {
  /** Visible label, associated with the control by Base UI (`<label for>`, or `aria-labelledby`). */
  label?: ReactNode;
  /** Helper text shown below the control, linked with `aria-describedby`. */
  hint?: ReactNode;
  /** Error message — marks the control invalid (`aria-invalid`) and replaces the hint. */
  error?: ReactNode;
  /**
   * Mark the control invalid without passing `error` — for layouts that render `Field.Error` /
   * `Field.Message` themselves. Implied by `error`.
   */
  invalid?: boolean;
  /** Shows the required marker on the label. Put `required` on the control too, for validation. */
  required?: boolean;
  /**
   * Render the label as a native `<label>` (default). Set to `false` for controls a `<label>`
   * can't name well, such as a `Select` trigger: the label becomes a `<div>` linked with `aria-labelledby`.
   */
  nativeLabel?: boolean;
  /** `id` for the hint/error element. Default: generated by Base UI. */
  messageId?: string;
  className?: string;
  /** The control: `Field.Control`, or a Base UI control such as `Select` or `Checkbox`. */
  children?: ReactNode;
}

/**
 * Wires a label, hint and error message to one form control, built on Base UI's `Field`.
 * Ids, `htmlFor`, `aria-describedby` and `aria-invalid` are handled for you.
 *
 * Validity is driven by the `error` prop (so it works with any form library); Base UI's native
 * constraint messages are not shown.
 *
 * ```tsx
 * <Field label="Company" hint="As it appears on invoices." error={errors.company} required>
 *   <Field.Control name="company" required />
 * </Field>
 * ```
 */
function FieldRoot({
  label,
  hint,
  error,
  invalid: invalidProp = false,
  required = false,
  nativeLabel = true,
  messageId,
  className,
  children,
  ...props
}: FieldProps) {
  const invalid = Boolean(error) || invalidProp;

  return (
    <FieldContext value={{ invalid, nativeLabel }}>
      <BaseField.Root className={cx(styles.field, className)} invalid={invalid || undefined} {...props}>
        {label && (
          <FieldLabel required={required} nativeLabel={nativeLabel} render={nativeLabel ? undefined : <div />}>
            {label}
          </FieldLabel>
        )}
        {children}
        <FieldMessage id={messageId} hint={hint} error={error} />
      </BaseField.Root>
    </FieldContext>
  );
}

export interface FieldLabelProps extends Omit<ComponentProps<typeof BaseField.Label>, 'className'> {
  /** Adds a red `*` hidden from assistive tech (the control's `required` is what gets announced). */
  required?: boolean;
  className?: string;
}

function FieldLabel({ required = false, className, children, ...props }: FieldLabelProps) {
  return (
    <BaseField.Label className={cx(styles.label, className)} {...props}>
      {children}
      {required && (
        <span className={styles.required} aria-hidden="true">
          *
        </span>
      )}
    </BaseField.Label>
  );
}

export interface FieldDescriptionProps extends Omit<ComponentProps<typeof BaseField.Description>, 'className'> {
  className?: string;
}

function FieldDescription({ className, ...props }: FieldDescriptionProps) {
  return <BaseField.Description className={cx(styles.message, className)} {...props} />;
}

export interface FieldErrorProps extends Omit<ComponentProps<typeof BaseField.Error>, 'className' | 'match'> {
  className?: string;
}

/** Always shown while mounted (render it only when there is an error). Renders a `<p>`. */
function FieldError({ className, ...props }: FieldErrorProps) {
  return <BaseField.Error match render={<p />} className={cx(styles.message, styles.error, className)} {...props} />;
}

export interface FieldMessageProps {
  hint?: ReactNode;
  error?: ReactNode;
  id?: string;
  className?: string;
}

/** The error if there is one, otherwise the hint; renders nothing when both are empty. */
function FieldMessage({ hint, error, id, className }: FieldMessageProps) {
  const message = error ?? hint;
  if (!message) return null;
  return error ? (
    <FieldError id={id} className={className}>
      {message}
    </FieldError>
  ) : (
    <FieldDescription id={id} className={className}>
      {message}
    </FieldDescription>
  );
}

/** @internal Read by text controls built on `Field` (`Field.Control`, `Textarea`). */
export function useFieldContext() {
  return useContext(FieldContext);
}

/**
 * Final props for a text control inside a `Field`: Base UI's props, then thira's overrides, then
 * the caller's own props (which win, as they would on a plain element).
 * - `aria-invalid` follows the `error` prop only, not Base UI's native constraint validity.
 * - `aria-labelledby` is dropped while the label is a native `<label for>`, which already names the control.
 * Pass the caller's `ref` to `BaseField.Control` instead: `mergeProps` keeps only the rightmost ref.
 * @internal
 */
export function fieldControlProps<T extends HTMLAttributes<HTMLElement>>(
  context: { invalid: boolean; nativeLabel: boolean },
  fieldProps: T,
  ownProps: T,
  overrides: Partial<T> = {},
): T {
  return mergeProps<'input'>(
    fieldProps as ComponentProps<'input'>,
    {
      ...(context.nativeLabel && { 'aria-labelledby': undefined }),
      'aria-invalid': context.invalid || undefined,
      ...overrides,
    } as ComponentProps<'input'>,
    ownProps as ComponentProps<'input'>,
  ) as T;
}

export interface FieldControlProps extends Omit<
  ComponentProps<'input'>,
  'size' | 'value' | 'defaultValue' | 'children'
> {
  value?: string | number | readonly string[];
  defaultValue?: string | number | readonly string[];
  /** Height and font size. */
  size?: 'sm' | 'md' | 'lg';
}

/** A styled `<input>` that takes its label, description and invalid state from the surrounding `Field`. */
function FieldControl({
  ref,
  id,
  disabled,
  value,
  defaultValue,
  name,
  size = 'md',
  className,
  ...props
}: FieldControlProps) {
  const context = useFieldContext();
  return (
    <BaseField.Control
      ref={ref}
      id={id}
      disabled={disabled}
      name={name}
      value={value}
      defaultValue={defaultValue}
      render={(fieldProps) => (
        <input
          {...fieldControlProps(context, fieldProps, props, {
            className: cx(styles.control, styles[size], className),
          })}
        />
      )}
    />
  );
}

/**
 * Compound field: `<Field label hint error>` wraps one control.
 * Parts for custom layouts: `Field.Label`, `Field.Control`, `Field.Description`, `Field.Error`, `Field.Message`.
 */
export const Field = Object.assign(FieldRoot, {
  Label: FieldLabel,
  Control: FieldControl,
  Description: FieldDescription,
  Error: FieldError,
  Message: FieldMessage,
});
